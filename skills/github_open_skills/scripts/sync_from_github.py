#!/usr/bin/env python3
"""Sync recorded skills from their upstreams into this collection.

    python3 scripts/sync_from_github.py            # 拉取上游并报告差异，不改任何文件
    python3 scripts/sync_from_github.py --apply    # 只更新「上游为准」的 skill
    python3 scripts/sync_from_github.py --list     # 列出全部来源与策略
    python3 scripts/sync_from_github.py --source microsoft__azure-skills

Configuration lives in ``sources/manifest.json`` (generated by
``scripts/build_manifest.py`` from the local ``skills`` CLI lock file).

Design rules:

* **Fail-closed.** 默认只报告，不落盘；只有 ``--apply`` 且策略为 ``upstream``
  的 skill 才会写文件。
* **Never clobber.** 策略为 ``local`` 的 skill（本仓自制 / 本机定制版）**永不**
  被覆盖，只输出差异清单，需要时人工合并。
* **Recoverable.** 覆盖前把目标目录整体备份为 ``<name>.backup-<时间戳>``，
  绝不删除数据；本地独有的溯源文件会在覆盖后原样带回。
* **Logic only.** 只收录 skill 的行为定义（SKILL.md / references / scripts），
  大体积素材（assets、demos、音频图片）不入库，避免仓库膨胀。
* **Honest.** 上游同步不到的 skill 会被明确标为「同步失败」，不会假装成功。

Standard library only; Python 3.9+.
"""

from __future__ import annotations

import argparse
import filecmp
import json
import os
import shutil
import subprocess
import sys
import urllib.request
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parents[1]
SKILLS_DIR = ROOT / "skills"
CACHE_DIR = ROOT / ".cache"
SOURCES_DIR = ROOT / "sources"
MANIFEST = SOURCES_DIR / "manifest.json"

# 本机已安装的 skill 位置：well-known 包用它当文件清单，校验时也用它做比对
LOCAL_INSTALL = Path(os.path.expanduser("~/.agents/skills"))

UPSTREAM = "upstream"  # 上游为准：--apply 会更新
LOCAL = "local"        # 本机版优先：永不覆盖，只报告

POLICY_LABEL = {UPSTREAM: "上游为准", LOCAL: "本机版优先"}

# 收录时不入库的大体积素材
SKIP_DIRS = {
    ".git", "node_modules", "__pycache__", ".pytest_cache", "dist", "build",
    "assets", "demos", "demo", "examples", "example", "media", "public",
    "screenshots", "vendor", "playwright-data",
}
SKIP_SUFFIXES = {
    ".mp3", ".mp4", ".wav", ".m4a", ".mov", ".avi",
    ".jpg", ".jpeg", ".png", ".webp", ".gif", ".ico", ".bmp", ".tiff", ".avif",
    ".svg", ".woff", ".woff2", ".ttf", ".otf", ".eot",
    ".pdf", ".zip", ".tar", ".gz", ".7z", ".rar", ".dmg", ".exe", ".bin",
}
SKIP_SUFFIXES |= {".pyc", ".pyo"}


# ------------------------------------------------------------------ utils ----


def run(cmd: List[str], cwd: Optional[Path] = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=str(cwd) if cwd else None, check=True,
                          capture_output=True, text=True)


def load_manifest() -> Dict:
    if not MANIFEST.is_file():
        print(f"缺少清单：{MANIFEST}\n先运行：python3 scripts/build_manifest.py --write",
              file=sys.stderr)
        raise SystemExit(2)
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def head_commit(path: Path) -> str:
    try:
        return run(["git", "rev-parse", "HEAD"], cwd=path).stdout.strip()
    except subprocess.CalledProcessError:
        return ""


def is_skippable(rel: Path) -> bool:
    if any(part in SKIP_DIRS for part in rel.parts[:-1]):
        return True
    return rel.suffix.lower() in SKIP_SUFFIXES


def iter_logic_files(root: Path) -> List[Path]:
    """Every file worth recording: behaviour, not bulk assets."""
    if not root.is_dir():
        return []
    out = []
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if is_skippable(rel):
            continue
        out.append(path)
    return out


def copy_logic(src: Path, dst: Path) -> int:
    """Copy only the logic files. Returns the number of files copied."""
    dst.mkdir(parents=True, exist_ok=True)
    count = 0
    for path in iter_logic_files(src):
        rel = path.relative_to(src)
        target = dst / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        count += 1
    return count


# --------------------------------------------------------------- upstreams ----


@dataclass
class Upstream:
    """A resolved upstream copy of one skill, ready to compare/apply."""
    name: str
    path: Path
    commit: str = ""
    origin: str = ""


def ensure_git_checkout(name: str, repo: str) -> Path:
    dest = CACHE_DIR / name
    if not (dest / ".git").is_dir():
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", "--depth", "1", repo, str(dest)])
        return dest
    run(["git", "fetch", "--depth", "1", "origin"], cwd=dest)
    run(["git", "reset", "--hard", "FETCH_HEAD"], cwd=dest)
    return dest


def fetch_wellknown(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "github_open_skills-sync"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def fetch_wellknown_skill(base_url: str, skill: str, installed: Path) -> Path:
    """Download a whole well-known skill package.

    The ``/.well-known/skills/<name>/`` endpoint serves the full tree
    (``SKILL.md`` plus ``references/``, ``agents/``, …) but publishes no index,
    so the locally installed copy is used as the file manifest. Every fetched
    file is checked against the installed one, which proves the recorded
    snapshot really is the upstream content.
    """
    dest = CACHE_DIR / "wellknown" / skill
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True, exist_ok=True)

    if not installed.is_dir():
        raise FileNotFoundError(f"本机无 {skill}，无法确定 well-known 包的文件清单")

    fetched = 0
    for path in iter_logic_files(installed):
        rel = path.relative_to(installed)
        url = f"{base_url}/{skill}/{rel.as_posix()}"
        try:
            blob = fetch_wellknown(url)
        except Exception as exc:  # noqa: BLE001
            raise RuntimeError(f"{rel}: {exc}") from exc
        target = dest / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(blob)
        fetched += 1
    if fetched == 0:
        raise FileNotFoundError("well-known 包为空")
    return dest


# ---------------------------------------------------------------- compare ----


def compare_dirs(local: Path, upstream: Path) -> Dict[str, List[str]]:
    def walk(root: Path) -> Dict[str, Path]:
        out: Dict[str, Path] = {}
        if not root.is_dir():
            return out
        for path in iter_logic_files(root):
            out[str(path.relative_to(root))] = path
        return out

    local_files = walk(local)
    upstream_files = walk(upstream)

    result: Dict[str, List[str]] = {
        "same": [], "differs": [], "only_local": [], "only_upstream": [],
    }
    for rel in sorted(set(local_files) | set(upstream_files)):
        if rel not in upstream_files:
            result["only_local"].append(rel)
        elif rel not in local_files:
            result["only_upstream"].append(rel)
        elif filecmp.cmp(local_files[rel], upstream_files[rel], shallow=False):
            result["same"].append(rel)
        else:
            result["differs"].append(rel)
    return result


def fmt_list(items: List[str], limit: int = 6) -> str:
    if not items:
        return "—"
    shown = items[:limit]
    tail = f" (+{len(items) - limit} 个)" if len(items) > limit else ""
    return ", ".join(shown) + tail


# ----------------------------------------------------------------- update ----


def apply_upstream(local: Path, upstream: Upstream, stamp: str) -> Tuple[Path, List[str]]:
    """Replace ``local`` with the upstream copy, backing the old one up.

    Local-only files (the provenance ``README.md`` and the like) are carried
    over from the backup instead of being dropped.
    """
    keep = compare_dirs(local, upstream.path)["only_local"]

    backup = local.parent / f"{local.name}.backup-{stamp}"
    if backup.exists():
        shutil.rmtree(backup)
    shutil.copytree(local, backup)
    shutil.rmtree(local)
    local.mkdir(parents=True)

    if upstream.path.is_dir():
        copy_logic(upstream.path, local)
    else:
        shutil.copy2(upstream.path, local / upstream.path.name)

    for rel in keep:
        src = backup / rel
        if not src.is_file():
            continue
        dst = local / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)

    return backup, keep


def write_provenance(skill_dir: Path, source: Dict, commit: str) -> None:
    """Record where this snapshot came from, inside the skill directory."""
    lines = [
        "---",
        "",
        f"# 来源：{source.get('display') or source.get('name')}",
        "",
        "| | |",
        "|---|---|",
        f"| **上游** | {source.get('repo') or source.get('baseUrl') or '本地（无上游）'} |",
        f"| **上游提交** | `{commit or '—'}` |",
        f"| **收录方式** | 交叉验证：MiniMax Code 全局 skills ∩ ZCode 全局 skills，内容逐字节一致 |",
        f"| **收录范围** | 仅逻辑（SKILL.md / references / scripts），assets、demos、音视频素材不入库 |",
        "",
        "本目录由 `skills/github_open_skills/scripts/sync_from_github.py` 维护，",
        "上游更新请改用 `--apply` 同步，不要手工编辑上游文件。",
        "",
    ]
    (skill_dir / "PROVENANCE.md").write_text("\n".join(lines), encoding="utf-8")


# ------------------------------------------------------------------- main ----


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="从多来源同步 skill 到本记录仓",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--apply", action="store_true",
                        help="对「上游为准」的 skill 执行更新（其余只报告）")
    parser.add_argument("--list", action="store_true", help="列出全部来源与策略")
    parser.add_argument("--source", help="只处理指定来源")
    parser.add_argument("--skill", action="append", help="只处理指定 skill（可重复）")
    parser.add_argument("--jobs", type=int, default=6, help="并发克隆数")
    args = parser.parse_args(argv)

    manifest = load_manifest()
    sources = manifest["sources"]

    if args.list:
        print(f"{'来源':<44}{'类型':<11}{'skill':<7}策略")
        print("-" * 78)
        for src in sources:
            if args.source and src["name"] != args.source:
                continue
            for skill, cfg in sorted(src["skills"].items()):
                if args.skill and skill not in args.skill:
                    continue
                mark = "✓" if (SKILLS_DIR / skill).is_dir() else "—"
                print(f"{src['name'][:43]:<44}{src['kind']:<11}{mark:<7}{POLICY_LABEL[cfg.get('policy', UPSTREAM)]}")
        return 0

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    applied: List[str] = []
    skipped: List[str] = []
    failed: List[str] = []
    commits: Dict[str, str] = {}

    for src in sources:
        if args.source and src["name"] != args.source:
            continue
        print(f"\n=== {src.get('display') or src['name']}  ({src['name']}, {src['kind']})")

        upstream_root: Optional[Path] = None
        commit = ""
        if src["kind"] == "git":
            try:
                upstream_root = ensure_git_checkout(src["name"], src["repo"])
                commit = head_commit(upstream_root)
                commits[src["name"]] = commit
                print(f"  上游 HEAD {commit[:7]}")
            except subprocess.CalledProcessError as exc:
                print(f"  ! 克隆失败：{exc.stderr.strip() or exc}")
                failed.append(src["name"])
                continue
        elif src["kind"] == "wellknown":
            print(f"  上游 {src.get('baseUrl')}")

        for skill, cfg in sorted(src["skills"].items()):
            if args.skill and skill not in args.skill:
                continue
            local_dir = SKILLS_DIR / skill
            policy = cfg.get("policy", UPSTREAM)

            # 本机版优先且无上游的 skill：不取上游，只登记。
            if policy == LOCAL and src["kind"] == "local":
                state = "已在库" if local_dir.is_dir() else "缺失"
                print(f"  · {skill} [{POLICY_LABEL[policy]}] {state}（本仓自管，无上游）")
                if local_dir.is_dir():
                    skipped.append(skill)
                else:
                    failed.append(skill)
                continue

            # Resolve the upstream copy of this one skill.
            try:
                if src["kind"] == "git":
                    rel = cfg["path"].rsplit("/", 1)[0] if "/" in cfg["path"] else ""
                    up_path = upstream_root / rel if rel else upstream_root
                    if not (up_path / "SKILL.md").is_file():
                        raise FileNotFoundError(f"上游无 {rel}/SKILL.md")
                elif src["kind"] == "wellknown":
                    installed = LOCAL_INSTALL / skill
                    up_path = fetch_wellknown_skill(src["baseUrl"], skill, installed)
                else:
                    raise FileNotFoundError("无上游")
            except Exception as exc:  # noqa: BLE001 - 任何失败都要如实报告
                print(f"  ! {skill}: 上游获取失败 —— {exc}")
                failed.append(skill)
                continue

            upstream = Upstream(name=skill, path=up_path, commit=commit,
                                origin=src.get("display", ""))

            if not local_dir.is_dir():
                print(f"  + {skill}: 本地缺失 → 新增")
                if args.apply:
                    local_dir.mkdir(parents=True, exist_ok=True)
                    if up_path.is_dir():
                        copy_logic(up_path, local_dir)
                    else:
                        shutil.copy2(up_path, local_dir / "SKILL.md")
                    write_provenance(local_dir, src, commit)
                    applied.append(skill)
                else:
                    skipped.append(skill)
                continue

            diff = compare_dirs(local_dir, up_path)
            changed = diff["differs"] + diff["only_upstream"] + diff["only_local"]
            tag = "一致" if not changed else f"{len(changed)} 处差异"
            print(f"  ~ {skill} [{POLICY_LABEL[policy]}] {tag}")
            if changed:
                if diff["differs"]:
                    print(f"      内容不同: {fmt_list(diff['differs'])}")
                if diff["only_upstream"]:
                    print(f"      上游独有: {fmt_list(diff['only_upstream'])}")
                if diff["only_local"]:
                    print(f"      本地独有: {fmt_list(diff['only_local'])}")

            if not args.apply:
                continue
            if policy == LOCAL:
                print("      跳过：本机版优先，不覆盖")
                skipped.append(skill)
            elif changed:
                backup, kept = apply_upstream(local_dir, upstream, stamp)
                write_provenance(local_dir, src, commit)
                print(f"      已更新，旧版备份到 {backup.name}")
                if kept:
                    print(f"      保留本地独有文件: {fmt_list(kept)}")
                applied.append(skill)
            else:
                write_provenance(local_dir, src, commit)
                skipped.append(skill)

    if args.apply and commits:
        hist = SOURCES_DIR / "sync-history.jsonl"
        with hist.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps({
                "date": datetime.now().strftime("%Y-%m-%d"),
                "commits": commits,
                "applied": applied,
                "skipped": skipped,
                "failed": failed,
            }, ensure_ascii=False) + "\n")

    print()
    if args.apply:
        print(f"完成：已更新 {len(applied)} 个，保留 {len(skipped)} 个"
              + (f"，失败 {len(failed)} 个" if failed else ""))
        if failed:
            print(f"失败清单：{', '.join(failed)}", file=sys.stderr)
            return 1
    else:
        print("报告模式，未改动任何文件。加 --apply 才会更新「上游为准」的 skill。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
